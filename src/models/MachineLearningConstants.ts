/** 学習・検証の下限しきい値 */

/** 学習に必要な最小出走行数 */
export const MIN_TRAINING_SAMPLES = 50;

/** walk-forward 検証に必要な最小レース数 */
export const MIN_WALK_FORWARD_RACES = 10;

/**
 * walk-forward の検証ブロックを開始するのに必要な最小学習レース数
 *
 * @remarks
 * 34次元のモデルを数十レース（数百出走行）で学習すると係数が安定せず、
 * ブロック1の指標が「モデルの汎化性能」ではなく「学習データ不足の症状」になる。
 * 実データ（227レース）で観測されたブロック別 log loss は
 * 学習72レースで 2.30 / 144レースで 2.43 / 204レースで 2.37 と単調ですらなく、
 * 学習量が足りない区間のばらつきが総合指標に混ざっていた。
 *
 * そこで既定を150レースとし、これを下回るブロックはスキップして
 * 総合指標からも除外する。`--min-train` で変更できる。
 */
export const DEFAULT_MIN_TRAIN_RACES = 150;

/**
 * 既定の L2 強度
 *
 * @remarks
 * `ml --validate` は学習窓の内側分割で λ を選ぶのでこの値を使わない。
 * 単発学習（`ml --train` / `predict`）のみが使う既定値。
 * 実データの内側分割ではどのブロックでも候補中で最も強い 100 が選ばれたため、
 * 旧既定の 1.0 から引き上げた（少データでは強く縮めたほうが汎化する）。
 */
export const DEFAULT_L2 = 100;
